// Extracts a curated subset of the icons in Torn's chat script (research/app.*.js)
// into userscript/src/generated/room-icons.ts.
// The icon table is evaluated with React stubs that render SVG markup strings.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const PICK = [
  'group', 'assault', 'attack_win', 'warlord', 'grenade_use', 'bounties', 'deadly', 'dead_bodies', 'hospitalize', 'mug',
  'crimes', 'jail', 'police_badge', 'security', 'weapon_bonus', 'armor', 'ammo', 'trade', 'item_market', 'points_market',
  'money', 'bank', 'stock', 'casino', 'poker', 'racing', 'travel_visa', 'plane', 'abroad', 'globe', 'star', 'announcements',
  'events', 'competitions', 'fun_games', 'gaming', 'music', 'drugs', 'gym', 'education', 'medical', 'missions', 'recruit_citizens',
  'tools_userscripts', 'wiki', 'question', 'discord', 'home', 'christmas_town_snowflake', 'halloween_pumpkin',
];

const file = readdirSync('research').find((f) => /^app\..*\.js$/.test(f));
const src = readFileSync(`research/${file}`, 'utf8');
const start = src.indexOf('var oC={');
const end = src.indexOf('},ob=Object.keys(oC)');
if (start < 0 || end < 0) throw new Error('icon table not found; the bundle changed');
const table = src.slice(start, end + 1);

const kebab = (k) => (k === 'className' ? 'class' : k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()));
const attrs = (p) => Object.entries(p).filter(([k, v]) => k !== 'children' && v != null && typeof v !== 'function' && typeof v !== 'object').map(([k, v]) => ` ${kebab(k)}="${String(v).replace(/"/g, '&quot;')}"`).join('');
const render = (tag, props, ...children) => {
  props = props || {};
  if (typeof tag === 'function') return tag({ ...props, children });
  return `<${tag}${attrs(props)}>${children.flat().join('')}</${tag}>`;
};

// Some table entries point at icon components defined elsewhere in the bundle
// (e.g. `bank:oh`); look those up by name as they are referenced.
function definition(name) {
  let at = src.indexOf(`function ${name}(e){`);
  if (at < 0) {
    const m = new RegExp(`[,;]${name}=function\\(e\\)\\{`).exec(src);
    if (!m) return null;
    at = m.index + name.length + 2;
  }
  let depth = 0;
  for (let i = src.indexOf('{', at); i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(at, i + 1);
  }
  return null;
}
const known = {
  N: () => ({ createElement: render }),
  rK: (props) => ({ viewBox: props.viewBox, inner: [props.children].flat(Infinity).join('') }),
  w: { _: (a, b) => Object.assign(a, b) },
  b: { _: (a) => ({ ...a }) },
};
const scope = new Proxy(known, {
  has: (t, k) => typeof k === 'string' && k !== 'globalThis',
  get(t, k) {
    if (k === Symbol.unscopables) return undefined;
    if (k in t) return t[k];
    const def = definition(String(k));
    t[k] = def ? new Function('scope', `with (scope) { return (${def}); }`)(scope) : () => null;
    return t[k];
  },
});
const table_ = new Function('scope', `with (scope) { return (${table.replace(/^var oC=/, '')}); }`)(scope);
const ctx = { oC: table_ };

const out = {};
for (const name of PICK) {
  const fn = ctx.oC[name];
  if (!fn) throw new Error('missing icon ' + name);
  const icon = fn({});
  out[name] = { viewBox: icon.viewBox ?? '0 0 24 24', inner: icon.inner };
}
// Other chat icons that are React components rather than captured DOM: back arrow, warning, create room.
const EXTRA = { back: 'ox', warning: 'oM', info: 'rQ', createRoom: 'dt', accessPublic: 'oq', accessPrivate: 'oL', accessExclusive: 'oB' };
const extra = {};
for (const [name, fn] of Object.entries(EXTRA)) {
  const icon = scope[fn]({});
  if (!icon || !icon.inner) throw new Error('missing component icon ' + fn);
  extra[name] = { viewBox: icon.viewBox ?? '0 0 24 24', inner: icon.inner };
}
writeFileSync(
  'userscript/src/generated/room-icons.ts',
  `// Generated by tools/gen-room-icons.mjs from Torn's chat bundle (${file}). Do not edit.\n` +
    `export const ROOM_ICONS: Record<string, { viewBox: string; inner: string }> = ${JSON.stringify(out, null, 1)};\n` +
    `export const COMPONENT_ICONS = ${JSON.stringify(extra, null, 1)} as const;\n`,
);
console.log(`room icons: ${PICK.length}, ${JSON.stringify(out).length} bytes`);
