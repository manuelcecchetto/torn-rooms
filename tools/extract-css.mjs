// Copies the rules of Torn's chat stylesheet that our markup uses, with every
// CSS-module class (name___hash) renamed to tr_name___hash, so the rooms look
// exactly like Torn's chat but never depend on (or collide with) Torn's live classes.
//
// Input: the newest research/app.*.css (download it from the <link> in Torn's page).
// Used classes: every name___hash token in userscript/src/**/*.ts (except generated/).
// Output: userscript/src/generated/torn-chat.css
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import postcss from 'postcss';

const TOKEN = /[A-Za-z][A-Za-z0-9-]*___[A-Za-z0-9_-]{5}(?![A-Za-z0-9_-])/g;

function files(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return f === 'generated' ? [] : files(p);
    return p.endsWith('.ts') ? [p] : [];
  });
}

const used = new Set();
for (const f of files('userscript/src')) for (const m of readFileSync(f, 'utf8').matchAll(TOKEN)) used.add(m[0]);

const cssFile = readdirSync('research').filter((f) => /^app\..*\.css$/.test(f)).map((f) => join('research', f)).sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs)[0];
const root = postcss.parse(readFileSync(cssFile, 'utf8'));
const rename = (s) => s.replace(TOKEN, (t) => 'tr_' + t);
const classTokens = (sel) => [...sel.matchAll(/\.([A-Za-z][A-Za-z0-9-]*___[A-Za-z0-9_-]{5})(?![A-Za-z0-9_-])/g)].map((m) => m[1]);

const varsUsed = new Set();
const animUsed = new Set();
const missing = new Set(used);

root.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const sels = rule.selectors.filter((sel) => {
    const toks = classTokens(sel);
    if (toks.length === 0) return false;
    return toks.every((t) => used.has(t));
  });
  if (sels.length === 0) {
    if (!/^(:root|\.dark-mode|:root \.dark-mode)$/.test(rule.selector)) rule.remove();
    return;
  }
  for (const sel of sels) for (const t of classTokens(sel)) missing.delete(t);
  rule.selectors = sels.map(rename);
  rule.walkDecls((d) => {
    for (const m of d.value.matchAll(/var\((--[A-Za-z0-9-]+)/g)) varsUsed.add(m[1]);
    if (/^animation(-name)?$/.test(d.prop)) for (const m of d.value.matchAll(TOKEN)) animUsed.add(m[0]);
    d.value = rename(d.value);
  });
});

// Theme variables: keep only the ones our rules read, scoped to our root.
root.walkRules((rule) => {
  if (!/^(:root|\.dark-mode|:root \.dark-mode)$/.test(rule.selector)) return;
  rule.walkDecls((d) => {
    if (!varsUsed.has(d.prop)) d.remove();
  });
  if (!rule.nodes.length) return rule.remove();
  rule.selector = rule.selector === ':root' ? '.tr-root' : '.dark-mode .tr-root';
});

root.walkAtRules((at) => {
  if (/keyframes$/.test(at.name)) {
    if (!animUsed.has(at.params.trim())) return at.remove();
    at.params = rename(at.params);
  }
});
root.walkAtRules((at) => {
  if (at.nodes && at.nodes.length === 0) at.remove();
});
root.walkComments((c) => c.remove());

const css = `/* Generated by tools/extract-css.mjs from Torn's ${cssFile.split('/').pop()}. Do not edit. */\n` + root.toString().replace(/\n{2,}/g, '\n');
writeFileSync('userscript/src/generated/torn-chat.css', css);
console.log(`classes used: ${used.size}, rules kept from ${cssFile}, css ${css.length} bytes`);
if (missing.size) console.log('no CSS rule for (fine for pure markers):', [...missing].join(' '));
