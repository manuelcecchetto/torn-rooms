// Turns SVGs captured from Torn's live chat (research/dom-svgs.json, via tools/chrome-eval.sh)
// into userscript/src/generated/icons.ts. Gradient ids become a placeholder so each use gets its own.
import { readFileSync, writeFileSync } from 'node:fs';

const svgs = JSON.parse(readFileSync('research/dom-svgs.json', 'utf8'));
const entries = Object.entries(svgs);
const pick = (test) => {
  const hit = entries.find(([k]) => test(k));
  if (!hit) throw new Error('icon not found: ' + test);
  return hit[1];
};
const settingsIcons = entries.filter(([k]) => k.includes('withTitle___U6QVy')).map(([, v]) => v);

const wanted = {
  chats: pick((k) => /\|root___mSyc0\|Your private chats$/.test(k)),
  arrow: pick((k) => k.includes('arrowIcon___RgJFw')),
  minimize: pick((k) => k.includes('minimizeIcon___Bk5cS')),
  flash: pick((k) => k.endsWith('|Flash enabled')),
  leave: pick((k) => k.endsWith('|Leave channel')),
  up: pick((k) => k.includes('iconUp___pHiRW')),
  dismiss: pick((k) => k.endsWith('|Dismiss new messages')),
  send: pick((k) => k.includes('icon___mMNXf')),
  tabChats: pick((k) => k.includes('icon___mLyRZ|Your private chats')),
  tabRecent: pick((k) => k.endsWith('|Recently Met')),
  tabFriends: pick((k) => k.endsWith('|Friends list')),
  tabFaction: pick((k) => k.endsWith('|Faction list')),
  tabBlocked: pick((k) => k.endsWith('|Blocked list')),
  search: pick((k) => k.includes('icon___aCVAk')),
  settings: pick((k) => /\|root___mSyc0\|Settings$/.test(k)),
  check: settingsIcons[0],
  cross: settingsIcons[1],
  globe: settingsIcons[2],
  refresh: settingsIcons[3],
  closeChat: pick((k) => k.includes('closeIcon___Ef2vS')),
  faction: pick((k) => k.includes('icon___vikBy')),
};

const out = {};
for (const [name, html] of Object.entries(wanted)) {
  const attr = (a) => (new RegExp(`<svg[^>]*\\s${a}="([^"]*)"`).exec(html) || [])[1] || null;
  const inner = html
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>$/, '')
    .replace(/ xmlns(:xlink)?="[^"]*"/g, '')
    .replace(/icon_gradient\d+_default/g, '__GID__');
  out[name] = { viewBox: attr('viewBox'), width: attr('width'), height: attr('height'), inner };
}
writeFileSync(
  'userscript/src/generated/icons.ts',
  `// Generated by tools/gen-icons.mjs from Torn's chat SVGs. Do not edit.\nexport const ICONS = ${JSON.stringify(out, null, 1)} as const;\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log('icons:', Object.keys(out).join(', '));
